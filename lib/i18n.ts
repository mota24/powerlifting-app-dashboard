const DICTIONNAIRES: Record<Langue, Record<CleTraduction, string>> = { fr, es }

/** Étiquette BCP-47, pour toLocaleDateString et compagnie. */
export const LOCALES: Record<Langue, string> = { fr: 'fr-FR', es: 'es-ES' }

/**
 * Langue lue dans profiles.langue. 'ca' est l'ancienne valeur du compte 2 :
 * elle reste lue comme de l'espagnol tant que la migration n'a pas tourné.
 */
export function langueDuProfil(valeur: unknown): Langue {
  return valeur === 'es' || valeur === 'ca' ? 'es' : 'fr'
}

export type Traducteur = (cle: CleTraduction, valeurs?: Record<string, string | number>) => string

export function traducteurPour(langue: Langue): Traducteur {
  const dico = DICTIONNAIRES[langue] ?? fr
  return (cle, valeurs) => {
    let texte = dico[cle] ?? fr[cle]
    if (valeurs) {
      for (const [nom, valeur] of Object.entries(valeurs)) {
        texte = texte.replaceAll(`{${nom}}`, String(valeur))
      }
    }
    return texte
  }
}
